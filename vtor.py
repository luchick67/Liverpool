a = [29, 10, 14, 37, 13]  # Создаем исходный неотсортированный список 
for i in range(len(a) - 1):  # Запускаем цикл  по индексам элементов 
    m = i  # Предполагаем, что текущий элемент  является минимальным 
    for j in range(i + 1, len(a)):  # Запускаем цикл j для поиска элемента меньше, чем m
        if a[j] < a[m]:  # Если нашли элемент, который строго меньше текущего минимального
            m = j  # Запоминаем индекс этого нового минимального элемента в переменную m         
    a[i], a[m] = a[m], a[i]  # Меняем местами текущий элемент i и найденный минимальный
    print(a)  # Выводим текущее состояние списка на экран после этого прохода