a =[12, 4, 9, 1, 6, 3]  # Создаем исходный неотсортированный список 'a'
b = [[x] for x in a]  # Разбиваем список на подсписки по одному элементу
while len(b) > 1:  # Крутим цикл, пока в нашем общем списке 'b' не останется один финальный массив
    n = []  # Создаем пустой список 'n' для результатов слияния на текущем шаге
    for k in range(0, len(b), 2):  # Шагаем по списку 'b' парами (через один элемент)
        if k + 1 < len(b):  # Если у текущего подсписка есть пара для слияния
            l = b[k]  # Запоминаем левый подсписок в переменную 'l'
            r = b[k + 1]  # Запоминаем правый подсписок в переменную 'r'
            res = [] # Создаем пустой список 'res' для сборки отсортированных элементов двух половин
            i = j = 0  # Сбрасываем указатели 'i' для левого и 'j' для правого подсписков в ноль
            while i < len(l) and j < len(r):  # Пока не дошли до конца одного из двух подсписков
                if l[i] < r[j]:  # Если элемент в левом подсписке меньше, чем в правом
                    res.append(l[i])  # Добавляем меньший элемент из 'l' в список 'res'
                    i += 1  # Сдвигаем левый указатель 'i' вперед
                else:  # Если элемент в правом подсписке меньше или равен
                    res.append(r[j])  # Добавляем меньший элемент из 'r' в список 'res'
                    j += 1  # Сдвигаем правый указатель 'j' вперед    
            res.extend(l[i:])  # Дописываем в 'res' остатки из левого списка 'l' (если они есть)
            res.extend(r[j:])  # Дописываем в 'res' остатки из правого списка 'r' (если они есть)
            n.append(res)  # Добавляем получившийся объединенный список в общую копилку 'n'
        else:  # Если у подсписка нет пары (он остался один в конце строки)
            n.append(b[k])  # Просто переносим его в следующий раунд без изменений
    b = n  # Заменяем старый список подсписков 'b' на новый, укрупненный список 'n'
print(a)  # Выводим исходный список на экран
print(b)  # Выводим полученный отсортированный список на экран