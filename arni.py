a = [2, 5, 8, 11, 14, 18, 21, 25, 30]  # Создаем список чисел 'a'
b = 18  # Создаем переменную 'b' с искомым числом

l = 0  # Задаем левую границу поиска 'l' (индекс 0)
r = len(a) - 1  # Задаем правую границу 'r' (индекс последнего элемента)
i = -1  # Создаем переменную ответа 'i' и пишем туда -1

while l <= r:  # Запускаем цикл, пока левая граница не пересечет правую
    m = (l + r) // 2  # Находим индекс середины 'm' путем деления нацело
    
    if a[m] == b:  # Если элемент посередине равен искомому числу 'b'
        i = m  # Записываем найденный индекс 'm' в переменную ответа 'i'
        break  # Срочно выходим из цикла, так как число уже найдено
    elif a[m] < b:  # Если центральный элемент списка меньше нашей цели 'b'
        l = m + 1  # Сдвигаем левую границу 'l' вправо, отсекая меньшую часть
    else:  # Если центральный элемент списка оказался больше нашей цели 'b'
        r = m - 1  # Сдвигаем правую границу 'r' влево, отсекая большую часть

print(i)  # Выводим финальное значение переменной 'i' на экран