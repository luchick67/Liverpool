a = [2, 5, 8, 11, 14, 18, 21, 25, 30]  # Создаем список чисел 
b = 18  # Создаем переменную  с искомым числом
l = 0  # Задаем левую границу поиска 
r = len(a) - 1  # Задаем правую границу 
i = -1  # Создаем переменную ответа 
while l <= r:  # Запускаем цикл, пока левая граница не пересечет правую
    m = (l + r) // 2  # Находим индекс середины  путем деления нацело
    if a[m] == b:  # Если элемент посередине равен искомому числу b
        i = m  # Записываем найденный индекс  в переменную ответа 
        break  #  выходим из цикла, так как число уже найдено
    elif a[m] < b:  # Если центральный элемент списка меньше b
        l = m + 1  # Сдвигаем левую границу вправо, отсекая меньшую часть
    else:  # Если центральный элемент списка оказался больше b
        r = m - 1  # Сдвигаем правую границу  влево, отсекая большую часть
print(i)  # Выводим финальное значение переменной  на экран