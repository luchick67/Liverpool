a = ["Анна", "Иван", "Мария", "Олег"]  # Создаем список участников 'a' с четырьмя именами
b = input("Введите имя для проверки: ")  # Запрашиваем имя у пользователя и сохраняем его в переменную 'b'
if b in a:  # Проверяем, есть ли текст из переменной 'b' внутри списка 'a'
    print("Участник найден")  # Если имя есть в списке, выводим это сообщение на экран
else:  # Если условия в 'if' не выполнилось (имени нет в списке)
    print("Участник не найден")  # Выводим на экран сообщение о том, что участник не найден