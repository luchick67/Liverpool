a = ["Анна", "Иван", "Мария", "Олег"]  # Создаем список участников  с четырьмя именами
b = input("Введите имя для проверки: ")  # Запрашиваем имя у пользователя 
if b in a:  # Проверяем, есть ли текст из b внутри списка 
    print("Участник найден")  # Если имя есть в  списке, выводим это сообщение на экран
else:  # Если условия  не выполнилось (имени нет в списке)
    print("Участник не найден")  # Выводим  на экран сообщение о том, что участник не найден